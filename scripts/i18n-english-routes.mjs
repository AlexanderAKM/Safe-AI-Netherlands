#!/usr/bin/env node
/**
 * Writes the English route tree, src/app/(en), from the pages in
 * src/app/[locale].
 *
 * Why: the site is a static export, so there is no middleware to serve
 * /courses from app/[locale]/courses with the locale "en". English instead
 * gets its own root layout in app/(en), and one small file per page there
 * that renders the shared page with locale "en". This script writes those
 * files, so nobody has to, and they cannot drift.
 *
 *   npm run i18n:routes          write app/(en) to match app/[locale]
 *   npm run i18n:routes -- --check   only report; exit 1 if out of date
 *
 * `npm run i18n:check` runs the --check form, in CI as well.
 *
 * A page in app/[locale] must export a default component that takes
 * `params` (with `locale`). If it exports generateMetadata or
 * generateStaticParams, the English file passes them through;
 * generateStaticParams is called without arguments, so it must not depend
 * on the locale.
 */
import { readdirSync, readFileSync, writeFileSync, mkdirSync, rmSync, existsSync, statSync } from "node:fs";
import { join, relative, dirname, sep } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const localeDir = join(root, "src", "app", "[locale]");
const englishDir = join(root, "src", "app", "(en)");
const check = process.argv.includes("--check");

function findPages(dir) {
  const pages = [];
  for (const entry of readdirSync(dir)) {
    const path = join(dir, entry);
    if (statSync(path).isDirectory()) pages.push(...findPages(path));
    else if (entry === "page.tsx") pages.push(path);
  }
  return pages;
}

function wrapperFor(source, rel) {
  const importPath = `@/app/[locale]/${rel.split(sep).join("/")}`.replace(/\/page\.tsx$/, "/page").replace(/^@\/app\/\[locale\]\/page\.tsx$/, "@/app/[locale]/page");
  const segments = dirname(rel).split(sep).filter((s) => s !== ".");
  const dynamic = segments
    .map((s) => s.match(/^\[(\w+)\]$/)?.[1])
    .filter(Boolean);
  const hasMetadata = /export\s+(async\s+)?function\s+generateMetadata\b/.test(source);
  const hasStaticParams = /export\s+(async\s+)?function\s+generateStaticParams\b/.test(source);
  const sourcePath = `src/app/[locale]/${rel.split(sep).join("/")}`;

  const imports = ["Page"];
  const named = [];
  if (hasMetadata) named.push("generateMetadata as localeMetadata");
  if (hasStaticParams) named.push("generateStaticParams as localeStaticParams");
  const importLine = named.length
    ? `import Page, {\n${named.map((n) => `  ${n},`).join("\n")}\n} from "${importPath}";`
    : `import ${imports[0]} from "${importPath}";`;

  const header = `/* Generated by scripts/i18n-english-routes.mjs; do not edit.
   Source: ${sourcePath}

   English lives at the root, without an /en prefix, so it has its own route
   tree; this file renders that page in English. Change the page there, and
   after adding or removing a page run \`npm run i18n:routes\`. */\n`;

  const lines = [header, importLine, ""];
  if (dynamic.length) {
    lines.push(`type Params = { ${dynamic.map((d) => `${d}: string`).join("; ")} };`, "");
    if (hasStaticParams) {
      lines.push("export function generateStaticParams() {", "  return localeStaticParams();", "}", "");
    }
    if (hasMetadata) {
      lines.push(
        "export function generateMetadata({ params }: { params: Params }) {",
        '  return localeMetadata({ params: { ...params, locale: "en" } });',
        "}",
        "",
      );
    }
    lines.push(
      "export default function EnglishPage({ params }: { params: Params }) {",
      '  return <Page params={{ ...params, locale: "en" }} />;',
      "}",
      "",
    );
  } else {
    if (hasMetadata) {
      lines.push(
        "export function generateMetadata() {",
        '  return localeMetadata({ params: { locale: "en" } });',
        "}",
        "",
      );
    }
    lines.push(
      "export default function EnglishPage() {",
      '  return <Page params={{ locale: "en" }} />;',
      "}",
      "",
    );
  }
  return lines.join("\n");
}

const expected = new Map();
for (const page of findPages(localeDir)) {
  const rel = relative(localeDir, page);
  expected.set(join(englishDir, rel), wrapperFor(readFileSync(page, "utf8"), rel));
}

const problems = [];
const existing = existsSync(englishDir) ? findPages(englishDir) : [];
for (const page of existing) {
  if (!expected.has(page)) problems.push({ kind: "stale", page });
}
for (const [page, content] of expected) {
  if (!existsSync(page)) problems.push({ kind: "missing", page, content });
  else if (readFileSync(page, "utf8") !== content) problems.push({ kind: "outdated", page, content });
}

if (check) {
  for (const p of problems) {
    console.error(`  ${p.kind}: ${relative(root, p.page)}`);
  }
  if (problems.length) {
    console.error("\nThe English routes in src/app/(en) do not match src/app/[locale]. Run `npm run i18n:routes`.");
    process.exit(1);
  }
  console.log(`English routes: ${expected.size} pages in src/app/(en) match src/app/[locale].`);
} else {
  for (const p of problems) {
    if (p.kind === "stale") {
      rmSync(p.page);
      console.log(`removed ${relative(root, p.page)}`);
    } else {
      mkdirSync(dirname(p.page), { recursive: true });
      writeFileSync(p.page, p.content);
      console.log(`wrote   ${relative(root, p.page)}`);
    }
  }
  console.log(`English routes: ${expected.size} pages, ${problems.length} changed.`);
}
